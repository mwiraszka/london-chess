// Regenerates src/app/constants/git-branch.generated.ts with the checked-out branch, which the
// environment tag shows outside production
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const FRONTEND_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = join(FRONTEND_ROOT, 'src/app/constants/git-branch.generated.ts');

const branchName = execFileSync('git', ['rev-parse', '--abbrev-ref', 'HEAD'], {
  encoding: 'utf8',
}).trim();

const banner = `// Generated by scripts/generate-branch-data.mjs.
// Do not edit by hand; it is rewritten before every serve, build and test run.`;

const output = `${banner}
export const GIT_BRANCH_NAME = ${JSON.stringify(branchName)};
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`git-branch.generated.ts written (${branchName})`);
