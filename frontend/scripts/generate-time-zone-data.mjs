// Regenerates src/app/constants/time-zone.generated.ts with the club's time zone, taken from
// the installed moment-timezone so it follows its updates. The package's own entry point
// loads every zone in the world, which the app has no use for
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// Matches CLUB_TIME_ZONE in src/app/constants/clubs.ts
const CLUB_TIME_ZONE = 'America/Toronto';

const require = createRequire(import.meta.url);
const moment = require('moment-timezone/moment-timezone-utils');
const data = require('moment-timezone/data/packed/latest.json');

const FRONTEND_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUT_PATH = join(FRONTEND_ROOT, 'src/app/constants/time-zone.generated.ts');

moment.tz.load(data);
const zone = moment.tz.zone(CLUB_TIME_ZONE);
if (!zone) {
  throw new Error(`moment-timezone has no data for ${CLUB_TIME_ZONE}`);
}

const banner = `// Generated by scripts/generate-time-zone-data.mjs.
// Do not edit by hand; it is rewritten before every serve, build and test run.`;

const output = `${banner}
export const CLUB_TIME_ZONE_DATA = ${JSON.stringify({ version: data.version, zones: [moment.tz.pack(zone)], links: [] }, null, 2)};
`;

writeFileSync(OUTPUT_PATH, output);
console.log(`time-zone.generated.ts written (${CLUB_TIME_ZONE}, ${data.version})`);
